/**
 * 태도(observe/accept)에 맞는 안내를 푼다. 기본은 관찰(observe).
 *
 * accept는 MBSR이 같은 실습을 다른 프레이밍으로 쓸 때의 경로다.
 * 같은 바디스캔이라도 관찰은 "무상을 본다", 수용은 "판단하지 않는다"로
 * 안내가 달라야 해서, 문구뿐 아니라 이름·맥락까지 태도가 갖고 있다.
 * MBSR을 붙일 때 실습을 새로 만들 필요 없이 attitude만 넘기면 된다.
 */
export const getAttitude = (practice, attitude = 'observe') => {
  const a = practice?.attitudes?.[attitude] || practice?.attitudes?.observe || {}
  return {
    ...a,
    title: a.title || practice?.title || '',
    context: a.context || practice?.context || '',
  }
}

/**
 * guided 스크립트를 총 시간(초)에 맞춰 구간 경계로 변환.
 * script의 w는 상대 가중치라, 5분을 고르든 15분을 고르든 같은 비율로 늘어난다.
 */
export function buildGuidedTimeline(script, totalSec) {
  const sum = script.reduce((acc, s) => acc + s.w, 0)
  let elapsed = 0
  return script.map((s, i) => {
    const dur = i === script.length - 1 ? totalSec - elapsed : Math.round((s.w / sum) * totalSec)
    const seg = { text: s.text, start: elapsed, dur }
    elapsed += dur
    return seg
  })
}

/** 몸 훑기 순서 — roundTrip이면 끝점을 겹치지 않게 되돌아온다. */
export function buildScanSequence(segments, roundTrip) {
  if (!roundTrip) return segments
  return [...segments, ...segments.slice(0, -1).reverse()]
}
